@app.get("/api/tokens")
def api_tokens():
    _load()

    # Max date in ledger for relative windows
    max_date_str = _credit_ledger["date"].max() if _credit_ledger.height > 0 else "2025-12-31"
    from datetime import date as _date
    _max_d = _date.fromisoformat(max_date_str)
    _cutoff_30d = (_max_d - timedelta(days=30)).isoformat()

    # Credit summary
    credit_a_minted = float(
        _credit_ledger.filter(
            (pl.col("credit_type") == "A") & (pl.col("amount") > 0)
        )["amount"].sum()
    )
    credit_a_converted = float(
        _credit_ledger.filter(pl.col("event_type") == "convert_to_B")["amount"].abs().sum()
    )
    credit_a_retained = round(credit_a_minted - credit_a_converted, 1)

    credit_b_converted = float(
        _credit_ledger.filter(pl.col("event_type") == "convert_from_A")["amount"].sum()
    )
    credit_b_face_value = round(credit_b_converted * CREDIT_B_USD, 2)

    # KYC revenue (pass-through)
    kyc_revenue = round(credit_a_minted * KYC_USD_PER_HEAD, 2)

    # Current balance per client and credit type
    last_bal = (
        _credit_ledger.sort("date")
        .group_by(["client_id","credit_type"])
        .agg(pl.last("balance_after").alias("balance"))
    )
    bal_a = {r["client_id"]: r["balance"] for r in last_bal.filter(pl.col("credit_type")=="A").iter_rows(named=True)}
    bal_b = {r["client_id"]: r["balance"] for r in last_bal.filter(pl.col("credit_type")=="B").iter_rows(named=True)}

    # 30-day Credit B burn
    spent_recent = (
        _credit_ledger
        .filter((pl.col("date") >= _cutoff_30d) & (pl.col("event_type") == "verify_spent"))
        .group_by("client_id")
        .agg(pl.col("amount").abs().sum().alias("b_spent_30d"))
    )
    spent_map = {r["client_id"]: r["b_spent_30d"] for r in spent_recent.iter_rows(named=True)}

    # 30-day Credit A earned
    earned_recent = (
        _credit_ledger
        .filter((pl.col("date") >= _cutoff_30d) & (pl.col("event_type") == "kyc_earned"))
        .group_by("client_id")
        .agg(pl.col("amount").sum().alias("a_earned_30d"))
    )
    earned_map = {r["client_id"]: r["a_earned_30d"] for r in earned_recent.iter_rows(named=True)}

    clients_out = []
    for row in _clients.iter_rows(named=True):
        cid   = row["client_id"]
        ctype = row["type"]
        is_issuer = (ctype == "FULL_KYC")
        ba = round(bal_a.get(cid, 0.0), 1)
        bb = round(bal_b.get(cid, 0.0), 1)
        a_earned = earned_map.get(cid, 0.0)
        b_spent = spent_map.get(cid, 0.0)
        runway = round(bb / (b_spent / 30 + 0.001), 1) if not is_issuer else 9999
        clients_out.append({
            "client_id":    cid,
            "name":         row["name"],
            "type":         ctype,
            "bal_a":        ba,
            "bal_b":        bb,
            "a_earned_30d": round(a_earned, 1),
            "b_spent_30d":  round(b_spent, 1),
            "runway_days":  runway,
        })

    # Monthly Credit A→B conversions
    monthly_conv = (
        _credit_ledger.filter(pl.col("event_type") == "convert_from_A")
        .with_columns(pl.col("date").str.slice(0, 7).alias("month"))
        .group_by("month")
        .agg(pl.sum("amount").alias("credit_b_converted"))
        .sort("month")
    )

    # Monthly Credit A earned
    monthly_a = (
        _credit_ledger.filter((pl.col("credit_type")=="A") & (pl.col("amount")>0))
        .with_columns(pl.col("date").str.slice(0, 7).alias("month"))
        .group_by("month")
        .agg(pl.sum("amount").alias("credit_a"))
        .sort("month")
    )

    low_b = [c for c in clients_out if c["bal_b"] < 20 and c["type"] == "ZKP_ONLY"]

    return {
        "credit_summary": {
            "credit_a_total_minted": round(credit_a_minted, 0),
            "credit_a_converted": round(credit_a_converted, 0),
            "credit_a_retained": credit_a_retained,
            "credit_b_converted": round(credit_b_converted, 0),
            "credit_b_face_value": credit_b_face_value,
            "kyc_revenue_usd": kyc_revenue,
        },
        "clients":     clients_out,
        "low_balance_alerts": low_b,
        "monthly_credit_a": {
            "months":   monthly_a["month"].to_list(),
            "credit_a": monthly_a["credit_a"].to_list(),
        },
        "monthly_conversions": {
            "months":            monthly_conv["month"].to_list(),
            "credit_b_converted": monthly_conv["credit_b_converted"].to_list(),
        },
    }


