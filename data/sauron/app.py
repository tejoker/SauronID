@app.get("/api/overview")
def api_overview():
    _load()

    total_verif = int(_verifications["total"].sum())
    total_full  = int(_verifications["full_kyc"].sum())
    total_red   = int(_verifications["reduced"].sum())
    total_fail  = int(_verifications["failed"].sum())

    # Unique registered users (personas who went through at least one KYC)
    unique_users = int(_sauron_users.height) if _sauron_users is not None else 0

    # KYC revenue: pass-through at $1/KYC
    kyc_revenue = round(total_full * KYC_USD_PER_HEAD, 2)

    # Query revenue: Credit B spent on attribute queries → USD
    total_b_spent = float(
        _credit_ledger.filter(pl.col("event_type") == "verify_spent")["amount"].abs().sum()
    )
    query_revenue = round(total_b_spent * CREDIT_B_USD, 2)

    # Credit A: minted vs converted → retained
    credit_a_minted = float(
        _credit_ledger.filter(
            (pl.col("credit_type") == "A") & (pl.col("amount") > 0)
        )["amount"].sum()
    )
    credit_a_converted = float(
        _credit_ledger.filter(pl.col("event_type") == "convert_to_B")["amount"].abs().sum()
    )
    credit_a_retained = round(credit_a_minted - credit_a_converted, 1)

    # Credit B: purchased + converted from A
    credit_b_purchased = float(
        _credit_ledger.filter(
            (pl.col("credit_type") == "B") & (pl.col("event_type") == "purchase")
        )["amount"].sum()
    )
    credit_b_converted = float(
        _credit_ledger.filter(pl.col("event_type") == "convert_from_A")["amount"].sum()
    )
    credit_b_face_value = round((credit_b_purchased + credit_b_converted) * CREDIT_B_USD, 2)

    # GDPR pending
    gdpr_pending = 0
    if _sauron_users is not None:
        from gdpr_purge import EU_EEA_COUNTRIES
        max_date = _verifications["date"].max() if _verifications.height > 0 else "2025-12-31"
        gdpr_pending = int(_sauron_users.filter(
            pl.col("country").is_in(list(EU_EEA_COUNTRIES)) &
            (pl.col("is_anonymized") == False)
        ).height)

    # Active client window: relative to max(date) in data
    max_date_str = _verifications["date"].max() if _verifications.height > 0 else "2025-12-31"
    from datetime import date as _date
    _max_d = _date.fromisoformat(max_date_str)
    _cutoff_90d = (_max_d - timedelta(days=90)).isoformat()
    _cutoff_chart = (_max_d - timedelta(days=90)).isoformat()

    active_clients = int(
        _verifications
        .filter(pl.col("date") >= _cutoff_90d)
        .select("client_id").unique().height
    )

    # daily Credit A earned and Credit B spent – last 90 days
    recent_a = (
        _credit_ledger
        .filter(
            (pl.col("date") >= _cutoff_chart) &
            (pl.col("credit_type") == "A") &
            (pl.col("event_type") == "kyc_earned")
        )
        .group_by("date")
        .agg(pl.sum("amount").alias("credit_a"))
        .sort("date")
    )
    recent_b = (
        _credit_ledger
        .filter(
            (pl.col("date") >= _cutoff_chart) &
            (pl.col("credit_type") == "B") &
            (pl.col("event_type") == "verify_spent")
        )
        .group_by("date")
        .agg(pl.sum("amount").alias("credit_b"))
        .sort("date")
    )
    recent = (
        recent_a.join(recent_b, on="date", how="outer_coalesce")
        .sort("date")
        .with_columns([
            pl.col("credit_a").fill_null(0.0),
            pl.col("credit_b").fill_null(0.0),
        ])
    )
    # ring sizes (latest snapshot)
    latest_ring = (
        _rings.sort("date")
        .group_by("ring_id")
        .agg(
            pl.last("ring_label").alias("label"),
            pl.last("member_count").alias("count"),
        )
        .sort("ring_id")
    )

    return {
        "kpis": {
            "total_verifications": total_verif,
            "total_full_kyc": total_full,
            "total_reduced": total_red,
            "total_failed": total_fail,
            "failure_rate": round(total_fail / max(total_verif, 1) * 100, 2),
            "active_clients": active_clients,
            "unique_registered_users": unique_users,
            "kyc_revenue_usd": kyc_revenue,
            "query_revenue_usd": query_revenue,
            "credit_a_total_minted": round(credit_a_minted, 0),
            "credit_a_retained": credit_a_retained,
            "credit_b_purchased": round(credit_b_purchased, 0),
            "credit_b_converted": round(credit_b_converted, 0),
            "credit_b_face_value": credit_b_face_value,
            "gdpr_pending": gdpr_pending,
        },
        "daily": {
            "dates":    recent["date"].to_list(),
            "credit_a": [round(v, 1) for v in recent["credit_a"].to_list()],
            "credit_b": [round(abs(v), 1) for v in recent["credit_b"].to_list()],
        },
        "rings": {
            "labels": latest_ring["ring_id"].to_list(),
            "names":  latest_ring["label"].to_list(),
            "counts": latest_ring["count"].to_list(),
        },
    }


